#!/usr/bin/env python3
"""Generate UI geometry and copy installed Hytale icons into the custom UI namespace."""
from pathlib import Path
import hashlib
import json
import math
import os
import struct
import zipfile
import zlib

ROOT = Path(__file__).resolve().parents[1] / 'src/main/resources/Common/UI/Custom/SoundCompass'
SOURCE_ICONS = {
    'GOBLIN': 'Common/UI/WorldMap/MapMarkers/GoblinBreachCompass.png',
    'FOOTSTEP': 'Common/Icons/ItemsGenerated/Hunt_Footprint.png',
    'SPRINT': 'Common/Icons/ItemsGenerated/Rocket_Boots.png',
    'COMBAT': 'Common/Icons/ItemsGenerated/Weapon_Sword_Iron.png',
    'AXE': 'Common/Icons/ItemsGenerated/Tool_Hatchet_Iron.png',
    'PICKAXE': 'Common/Icons/ItemsGenerated/Tool_Pickaxe_Iron.png',
    'CREATURE': 'Common/UI/WorldMap/MapMarkers/HuntSite.png',
    'INTERACTION': 'Common/UI/WorldMap/MapMarkers/Home.png',
    'ENVIRONMENT': 'Common/UI/WorldMap/MapMarkers/Campfire.png',
    'OTHER': 'Common/UI/WorldMap/MapMarkers/Coordinate.png',
}
ICONS = {name: f'Icons/{name}.png' for name in SOURCE_ICONS}


def copy_icons():
    assets = Path(os.environ.get('HYTALE_ASSETS', str(Path.home() / '.var/app/com.hypixel.HytaleLauncher/data/Hytale/install/release/package/game/latest/Assets.zip')))
    (ROOT / 'Icons').mkdir(exist_ok=True)
    provenance = {}
    with zipfile.ZipFile(assets) as archive:
        for name, source in SOURCE_ICONS.items():
            contents = archive.read(source)
            assert contents.startswith(b'\x89PNG\r\n\x1a\n'), source
            (ROOT / ICONS[name]).write_bytes(contents)
            provenance[ICONS[name]] = {'source': source, 'sha256': hashlib.sha256(contents).hexdigest()}
    (ROOT / 'icon-sources.json').write_text(json.dumps(provenance, indent=2) + '\n')


def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def arc(degrees):
    # A compact patch around the arc, not a full-screen texture per angle.
    # 360 x 128px patches use about 23 MiB of raw texture memory in total.
    size = 128
    angle = math.radians(degrees)
    centre_x, centre_y = math.sin(angle) * 190, -math.cos(angle) * 190
    rows = bytearray()
    for y in range(size):
        rows.append(0)
        for x in range(size):
            dx, dy = x + .5 - size / 2 + centre_x, y + .5 - size / 2 + centre_y
            distance = math.hypot(dx, dy)
            delta = abs((math.atan2(dx, -dy) - angle + math.pi) % (math.pi * 2) - math.pi)
            alpha = max(0, min(1, 4 - abs(distance - 190)))
            alpha *= max(0, min(1, (math.radians(17) - delta) * 190))
            rows.extend((255, 225, 155, int(230 * alpha)))
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
    data += chunk(b'IDAT', zlib.compress(rows)) + chunk(b'IEND', b'')
    (ROOT / 'Arcs' / f'{degrees:03}.png').write_bytes(data)


def ui(large):
    size, icon_size, patch = (640, 64, 160) if large else (500, 48, 122)
    out = ['// Generated by tools/generate_resources.py. Icons are bundled beside these documents.']
    out += [f'@Arc{degree:03} = PatchStyle(TexturePath: "Arcs/{degree:03}.png");' for degree in range(360)]
    out += ['Group #SoundCompassRoot {', '  LayoutMode: CenterMiddle;', '  HitTestVisible: false;',
           '  Group #CompassCanvas {', f'    Anchor: (Width: {size}, Height: {size});']
    for i in range(9):
        out += [f'    Group #Cue{i} {{', f'      Anchor: (Left: 0, Top: 0, Width: {size}, Height: {size});', '      Visible: false;']
        if i < 8:
            out += [f'      Group #Arc{i} {{', f'        Anchor: (Left: 0, Top: 0, Width: {patch}, Height: {patch});',
                    '        Background: @Arc000;', '      }']
        out += [f'      Group #Marker{i} {{', f'        Anchor: (Left: 0, Top: 0, Width: {icon_size}, Height: {icon_size});']
        for name, path in ICONS.items():
            out += [f'        Group #Icon{i}{name} {{', f'          Anchor: (Left: 0, Top: 0, Width: {icon_size}, Height: {icon_size});', '          Visible: false;']
            if name == 'FOOTSTEP':
                out += ['          Background: #eedcb4;', '          Group {', f'            Anchor: (Left: 0, Top: 0, Width: {icon_size}, Height: {icon_size});', f'            Background: "{path}";', '          }']
            else:
                out += [f'          Background: "{path}";']
            out += ['        }']
        out += ['      }', '    }']
    out += ['  }', '}']
    (ROOT / ('Large.ui' if large else 'Standard.ui')).write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    ROOT.mkdir(parents=True, exist_ok=True)
    (ROOT / 'Arcs').mkdir(exist_ok=True)
    for obsolete in ROOT.glob('Arc[0-7].png'):
        obsolete.unlink()
    copy_icons()
    for i in range(360):
        arc(i)
    ui(False)
    ui(True)
    print('Generated 360 compact ring angles and both HUD sizes.')
